-- 기준일은 2026-10-02, 반납 기한은 대출일의 14일 뒤로 가정합니다.
SELECT
    COUNT(*) AS total,
    COUNT(CASE WHEN return_date IS NOT NULL THEN 1 END) AS returned,
    COUNT(CASE WHEN return_date IS NULL THEN 1 END) AS active,
    COUNT(CASE WHEN return_date IS NULL
        AND date(loan_date,'+14 days') < '2026-10-02'
        THEN 1 END) AS overdue,
    COUNT(CASE WHEN return_date IS NULL
        AND date(loan_date,'+14 days') = '2026-10-02'
        THEN 1 END) AS due_today,
    COUNT(CASE WHEN return_date IS NULL
        AND date(loan_date,'+14 days') > '2026-10-02'
        THEN 1 END) AS not_due
FROM loans;
